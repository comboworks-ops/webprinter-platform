const byHash = new Map(ONLINETRYKSAGER_ENTRIES.filter(e=>e.role==='product').map(e=>[e.sha256,e]));
export function studioPackEntry(metadata: Record<string,unknown> | null | undefined) {
  if (metadata?.referencePackId !== ONLINETRYKSAGER_PACK_ID || typeof metadata.sourceSha256 !== 'string') return undefined;
  return byHash.get(metadata.sourceSha256);
}
export function selectStudioPackReference<T extends {id:string;product_key:string;is_active:boolean;metadata:Record<string,unknown>}>(assets:T[], productKey:string, preferredId?:string) {
  const matches = assets.filter(a=>a.is_active && a.product_key===productKey && studioPackEntry(a.metadata)?.productKey===productKey);
  if (preferredId) {
    const selected=matches.find(a=>a.id===preferredId);
    if (!selected) throw new Error('Den valgte produktreference er ikke tilgængelig for dette produkt.');
    return selected;
  }
  return matches.sort((a,b)=>Number(studioPackEntry(b.metadata)!.preferred)-Number(studioPackEntry(a.metadata)!.preferred) || studioPackEntry(a.metadata)!.index-studioPackEntry(b.metadata)!.index || a.id.localeCompare(b.id))[0];
}
